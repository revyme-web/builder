// render-resolved-mutations.ts — the ONE list of mutation types whose visual
// result is computed at RENDER time and therefore cannot be represented by the
// instant inline `patchStyles` the imperative-first path applies.
//
// Deliberately a LEAF module (zero imports): both `mutation-queue.ts` (which
// owns the flush) and `canvas/node-ops.ts` (which owns the style routing) read
// it, and a dozen test files mock `mutation-queue` — hanging the constant off
// that module would force every one of those mocks to re-export it.
//
// ── Why these types need a render ────────────────────────────────────────────
// Two distinct storage shapes, same consequence:
//
//   • Stylesheet-backed (`@media`/`@container`, `:lang()`, `::before/::after`,
//     `:hover`): the rule text is regenerated by `renderNodes` when it injects
//     the page CSS. Clearing the element's inline value only re-exposes the OLD
//     baked rule — the removal is invisible until a render drops the rule.
//
//   • Render-resolved (variant objects, per-variant `conditionalStyles`
//     ternaries, variant-scoped variable bindings): the painted value is the
//     `{...base, ...default, ...variant}` merge `resolveVariantStyles` computes.
//     Clearing the inline patch removes the property ENTIRELY instead of falling
//     back to the base — a wrong intermediate that only a render corrects.
//
// So a flush carrying one of these must NOT arm the canvas-update render skip
// (`onBeforeFlush` in useMutationQueueLifecycle), and a REMOVAL routed into one
// of them must force a render (`forceRenderAfterExternalEdit` in node-ops).
//
// Guarding only `updateContainerStyle` (the pre-2026-07-25 behaviour) is why
// "Reset Override" landed in code but not on the canvas roughly every other
// time: whether the DOM caught up depended on some unrelated later render
// happening to fire.

/** Mutation types whose visual result is render-resolved. See the module doc.
 *  (Named `…_STYLE_MUTATIONS` until 2026-07-25 — CMS field bindings belong to
 *  the same category and aren't styles, so the name dropped the qualifier.) */
export const RENDER_RESOLVED_MUTATIONS: ReadonlySet<string> = new Set([
  // ── Stylesheet-backed ──
  'updateContainerStyle',
  'clearContainerStyles',
  'updateLocaleStyle',
  'updatePseudoStyle',
  'removePseudo',
  'updateCssHover',
  'removeCssHover',
  // ── Render-resolved (variant merge / per-variant ternaries) ──
  'updateVariantStyle',
  'setConditionalStyle',
  'setConditionalOrder',
  'setVariantVisibility',
  'setVariantCmsStyle',
  'setVariantAttr',
  'setVariantInlineVariable',
  'setVariantBorderVariable',
  'removeVariantStyleVariable',
  // ── Per-viewport `__mq` ternary bindings (resolved by the parser + Renderer,
  //    never by an inline patch) ──
  'bindResponsiveStyleVariable',
  'unbindResponsiveStyleVariable',
  'setResponsiveStyleBase',
  // ── CMS field bindings ──
  // The painted value of `{item.title}` is produced by `applyNodeCmsBindings`
  // at RENDER time, per row, from the collection data — there is no inline
  // patch that could express it. Binding, unbinding or re-pointing a field is
  // therefore invisible until a render runs: pressing × on the Content pill
  // rewrote the JSX correctly but every row kept painting the old value until
  // a page switch (user report 2026-07-25). Same shape as the variant/@media
  // entries above.
  'bindField',
  'unbindField',
  'bindStyleToMap',
  'bindPropToMap',
  'unbindPropFromMap',
  'setVariantCmsText',
  'clearCmsOrphan',
  'setCmsNavHref',
  'changeCollectionSource',
  'bindToCmsCollection',
  'unbindFromCmsCollection',
]);

/** True when a flush carries at least one mutation whose visual result is
 *  render-resolved — i.e. the post-flush render must NOT be skipped.
 *
 *  Kept for `forceRenderAfterExternalEdit`'s routing in node-ops; the flush
 *  gate itself now asks the inverted question (`flushIsFullyImperative`). */
export function flushNeedsRender(mutationTypes: readonly string[]): boolean {
  return mutationTypes.some((t) => RENDER_RESOLVED_MUTATIONS.has(t));
}

// ─── The render-skip gate (inverted 2026-07-25) ─────────────────────────────
//
// The imperative-first drag architecture patches the DOM inline and then queues
// the matching mutation, so re-rendering after that flush would be redundant
// work. `onBeforeFlush` therefore arms a one-shot skip.
//
// That skip used to be the DEFAULT: any flush not in `RENDER_RESOLVED_MUTATIONS`
// suppressed its render. But the allow-list can only ever list what someone
// remembered to add, so EVERY mutation type nobody thought about — CMS bindings,
// slot connect/disconnect, layers DnD, … — silently landed in the code and never
// in the DOM until a page switch. That produced a steady drip of "the code
// updated but the canvas didn't" reports, each fixed one call site at a time.
//
// So the question is inverted. A flush may skip its render ONLY when every
// mutation in it was ALREADY applied to the DOM imperatively. The set below is
// small, closed, and owned by the drag/style hot path — everything else renders.
// A new mutation type is now safe by default: worst case one redundant render,
// instead of an invisible edit.
//
// Note the hot path has a SECOND guard: `interacting` (set for the duration of a
// drag / slider gesture) blocks renders independently, so inverting this flag
// does not add renders mid-gesture — it only affects discrete, committed edits.

/** Mutation types whose visual result is applied to the DOM imperatively
 *  BEFORE the mutation is queued (`patchNodeStyles` → `queueMutation`), so the
 *  post-flush render would be pure redundant work. */
export const IMPERATIVELY_PATCHED_MUTATIONS: ReadonlySet<string> = new Set([
  // The 60fps style write — drag position, resize dimensions, every slider and
  // colour-picker commit. `node-ops.updateNodeStyles` patches the element (or
  // the bridge) first, so the DOM is already correct when this flushes.
  'updateStyles',
]);

/** True when EVERY mutation in the flush is already reflected in the DOM, so
 *  the post-flush render can be skipped. An empty flush is not skippable. */
export function flushIsFullyImperative(mutationTypes: readonly string[]): boolean {
  return mutationTypes.length > 0
    && mutationTypes.every((t) => IMPERATIVELY_PATCHED_MUTATIONS.has(t));
}

/**
 * The post-flush render-skip decision, as a pure function.
 *
 *   'arm-skip'    — every mutation was already applied to the DOM imperatively;
 *                   the render would be redundant work.
 *   'disarm-skip' — this flush carries something the imperative patch CAN'T
 *                   express, so any skip flag armed earlier must be cleared.
 *                   The flag is not only set here: `node-ops.updateNodeStyles`
 *                   marks it directly whenever it patches the DOM, so a style
 *                   write moments earlier would otherwise eat this render
 *                   (applying a background video queues `setVideoFill` + an
 *                   `updateStyles` that clears the competing fills; the style
 *                   write armed the skip and the `<video>` never appeared —
 *                   user trace 2026-07-26).
 *   'leave'       — a higher-priority state owns the decision: text editing, a
 *                   pending structural change, or an explicit force-render.
 *
 * `consumeForceRender` is a callback because it has a SIDE EFFECT (it clears
 * the one-shot flag) and the original call order — text-editing and
 * structural-pending checked FIRST, so the flag SURVIVES to the next flush when
 * either is true — is behaviour, not an implementation detail.
 */
export type FlushRenderGate = 'arm-skip' | 'disarm-skip' | 'leave';

export function decideFlushRenderGate(args: {
  mutationTypes: readonly string[];
  isTextEditing: boolean;
  isStructuralPending: boolean;
  consumeForceRender: () => boolean;
}): FlushRenderGate {
  const { mutationTypes, isTextEditing, isStructuralPending, consumeForceRender } = args;
  const skippable = flushIsFullyImperative(mutationTypes);
  if (!isTextEditing && !isStructuralPending && !consumeForceRender() && skippable) return 'arm-skip';
  return skippable ? 'leave' : 'disarm-skip';
}
